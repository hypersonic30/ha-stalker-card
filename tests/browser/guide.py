from _server import *

C, O = "stalker-card >> ", ".stalker-card-overlay >> "

serve()
with sync_playwright() as p:
    b, pg, errors = browser_page(p)
    open_card(pg)
    pg.wait_for_selector(C + ".sc-ch")
    pg.locator(C + ".sc-tab", has_text="Programm").click()
    pg.wait_for_selector(C + ".sc-gp")
    rows = pg.locator(C + ".sc-grow").count()
    check("guide lists only channels with a programme (25 of 66) + Mehr", rows == 25 and "(41)" in pg.inner_text(C + "[data-action=gmore]"), rows)
    gcalls = [c for c in calls() if c[1].startswith("guide?")]
    check("guide asks for the visible channels in one request", len(gcalls) == 1 and gcalls[0][1].count("%2C") == 24, [c[1][:80] for c in gcalls])
    check("guide window is sent as from/to", "from=" in gcalls[0][1] and "to=" in gcalls[0][1])
    check("programmes are placed on a time axis (distinct left offsets)", pg.evaluate("() => new Set([...card.shadowRoot.querySelector('.sc-grow').querySelectorAll('.sc-gp')].map(e => e.style.left)).size") > 3)
    check("time header and now line exist", pg.locator(C + ".sc-gtick").count() >= 40 and pg.locator(C + ".sc-gnow").count() == 1)
    check("guide starts scrolled to now", pg.evaluate("() => card.shadowRoot.querySelector('.sc-guide').scrollLeft") > 100)
    check("channel column and header are sticky", pg.evaluate("() => getComputedStyle(card.shadowRoot.querySelector('.sc-gch')).position + getComputedStyle(card.shadowRoot.querySelector('.sc-gtime')).position") == "stickysticky")
    check("programme title is escaped", pg.locator(C + ".sc-gp u").count() == 0 and "<u>x</u>" in pg.inner_text(C + ".sc-gp"))
    pg.locator(C + "[data-action=gmore]").click()
    pg.wait_for_function("() => card.shadowRoot.querySelectorAll('.sc-grow').length === 50")
    n = len([c for c in calls() if c[1].startswith("guide?")])
    check("Mehr loads only the new channels", n == 2 and "%2C" in [c for c in calls() if c[1].startswith("guide?")][-1][1])
    pg.locator(C + ".sc-gp.now").first.click()
    pg.wait_for_selector(O + ".sc-sheet")
    t = pg.inner_text(O + ".sc-sheet")
    check("programme sheet: title, channel, description, running", "Sendung" in t and "Kanal" in t and "Beschreibung" in t and "Läuft jetzt" in t, t[:200])
    check("description is escaped", pg.locator(O + ".sc-summary b").count() == 0)
    pg.locator(O + "[data-action=play_live]").click()
    pg.wait_for_function("() => { const v = document.querySelector('.stalker-card-overlay').shadowRoot.querySelector('video'); return v && v.currentTime > 1 }", timeout=30000)
    check("Sender ansehen plays the channel", any(c[1] == "play" and c[2]["kind"] == "live" for c in calls()))
    check("detail sheet closed when playing", not pg.evaluate("() => document.querySelector('.stalker-card-overlay').shadowRoot.getElementById('sc-detail').open"))
    pg.locator(O + "[data-action=close_player]").click()
    pg.wait_for_timeout(300)
    pg.fill(C + "input[data-q]", "kanal 033")
    pg.wait_for_function("() => card.shadowRoot.querySelectorAll('.sc-grow').length === 1")
    check("search works in the guide", True)
    pg.locator(C + ".sc-gch").click()
    pg.wait_for_function("() => { const v = document.querySelector('.stalker-card-overlay').shadowRoot.querySelector('video'); return v && v.currentTime > 1 }", timeout=30000)
    check("tapping the channel in the guide plays it", [c for c in calls() if c[1] == "play"][-1][2]["id"] == "33")
    check("no page errors", not errors, errors)
    b.close()
finish()
